def demo_data() -> dict:
    """Создать независимый набор из восьми партий по одной штуке."""
    examples = (
        ("Кастрюля 5 л", 1, 125050), ("Нож поварской", 2, 85000),
        ("Сковорода", 1, 180000), ("Доска разделочная", 3, 45000),
        ("Половник", 4, 32000), ("Венчик", 3, 28000),
        ("Дуршлаг", 3, 65000), ("Противень", 5, 95000),
    )
    items = []
    for number, (name, category, price) in enumerate(examples, 1):
        items.append({
            "id": number, "name": name, "category_id": category,
            "state_id": 1, "room_id": 1, "quantity": 1,
            "unit_price": price,
        })
    return {"version": 1, "items": items, "moves": []}
